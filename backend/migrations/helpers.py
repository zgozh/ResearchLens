def ensure_tables(tables: dict, bind) -> None:
    """按依赖顺序建表（checkfirst=True，幂等）。"""
    for name, table in tables.items():
        table.create(bind, checkfirst=True)
        for idx in table.indexes:
            try:
                idx.create(bind, checkfirst=True)
            except Exception:  # noqa: BLE001  索引已存在/方言差异不阻断
                pass


def ensure_columns(bind, table: str, columns: dict[str, sa.types.TypeEngine]) -> None:
    """为已存在表补列（SQLite / Postgres 通用，忽略重复）。"""
    insp = sa.inspect(bind)
    if table not in insp.get_table_names():
        return
    existing = {c["name"] for c in insp.get_columns(table)}
    for name, type_ in columns.items():
        if name in existing:
            continue
        try:
            bind.execute(sa.text(f'ALTER TABLE "{table}" ADD COLUMN "{name}" {type_.compile(bind.dialect)}'))
        except Exception:  # noqa: BLE001  并发/方言差异
            pass
