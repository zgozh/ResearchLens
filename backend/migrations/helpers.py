"""迁移辅助：以 ``checkfirst=True`` 建表，兼容「旧库已由 create_all 建过一部分」的现场。

设计取舍：迁移文件不追求与 ORM 定义 1:1 自动推导，而是显式声明 canonical 表，
这样 SQLite（需要 batch 模式）与 Postgres 的行为一致，且重复执行幂等。
"""
from __future__ import annotations

import sqlalchemy as sa

_md = sa.MetaData()


def _pk_str() -> sa.Column:
    return sa.Column("id", sa.String(36), primary_key=True)


def _pk_int() -> sa.Column:
    """旧表（legacy）主键：保留原有 int 身份（PaperId/JobId/LegacyEvidenceId 均为正整数）。"""
    return sa.Column("id", sa.Integer, primary_key=True, autoincrement=True)


def T(name: str, *cols, **kw) -> sa.Table:
    """构造（并缓存）表对象。"""
    if name in _md.tables:
        return _md.tables[name]
    return sa.Table(name, _md, *cols, **kw)


def has_table(name: str) -> bool:
    return name in _md.tables


# ------------------------------------------------------------------ 共享列

def _created() -> sa.Column:
    return sa.Column("created_at", sa.DateTime())


def _updated() -> sa.Column:
    return sa.Column("updated_at", sa.DateTime())


# ------------------------------------------------------------------ 表定义

